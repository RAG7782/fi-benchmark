def generate_framework(domain: str, task: str, model: str = "claude-sonnet-4-6") -> str:
    """Generate a complete injectable framework for the domain."""
    client = anthropic.Anthropic()

    meta_prompt = f"""You are a Framework Injection specialist. Generate a complete, injectable reasoning framework for the following domain and task type.

The framework must contain ALL FIVE types:

1. DECLARATIVE — Knowledge hierarchy, source rankings, foundational concepts with HIGH semiotic density terms
2. PROCEDURAL — Step-by-step expert reasoning method for this specific type of analysis
3. EVALUATIVE — Quality criteria, how to judge if the analysis is good
4. ETHICAL — Hard constraints, what must never be done, compliance requirements
5. COMPOSITIONAL — How the above combine, the end-to-end workflow

Use domain-specific terms of HIGH semiotic density. Each key term should activate a specific professional frame. Be specific to THIS domain, not generic.

DOMAIN: {domain}
TYPICAL TASK: {task}

Generate the framework as a complete system prompt that an AI agent would internalize."""

    message = client.messages.create(
        model=model,
        max_tokens=6000,
        messages=[{"role": "user", "content": meta_prompt}]
    )
    return message.content[0].text


def get_pe_prompt(case: dict) -> str:
    """Prompt Engineering: simple task instruction."""
    return f"{case['task']}\n\n{case['test_input']}"


def get_ce_prompt(case: dict) -> str:
    """Context Engineering: task + rich context."""
    return f"""You are a senior expert in {case['domain']} with decades of experience.

Context: This is a real-world case requiring deep domain expertise. Consider all relevant factors, precedents, regulations, best practices, and ethical considerations. Be thorough, systematic, and actionable.

Source context: {case['source']}

Task: {case['task']}

Case Details:
{case['test_input']}

Provide a comprehensive, well-structured expert analysis."""


def get_fi_prompt(case: dict, framework: str) -> str:
    """Framework Injection: full injectable framework + task."""
    return f"""{framework}

---

Now apply this framework rigorously to the following case:

Source: {case['source']}

Task: {case['task']}

Case Details:
{case['test_input']}"""


