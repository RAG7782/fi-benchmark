def run_hard_benchmark(
    domain_indices: list = None,
    models: list = None,
    output_dir: str = "results/hard"
):
    """Run the hard benchmark."""

    if models is None:
        models = ["claude-haiku-4-5-20251001", "claude-sonnet-4-6"]
    if domain_indices is None:
        domain_indices = list(range(len(HARD_CASES)))

    cases = [HARD_CASES[i] for i in domain_indices]

    Path(output_dir).mkdir(parents=True, exist_ok=True)
    Path("frameworks/hard").mkdir(parents=True, exist_ok=True)

    timestamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    results = {
        "metadata": {
            "timestamp": timestamp,
            "type": "hard_benchmark",
            "cases": [c["id"] for c in cases],
            "models": models,
            "eval_model": "claude-sonnet-4-6"
        },
        "results": []
    }

    # Generate frameworks
    print("=" * 70)
    print("STEP 1: Generating frameworks for FI condition")
    print("=" * 70)

    frameworks = {}
    for case in cases:
        fw_path = f"frameworks/hard/{case['id']}.md"
        if Path(fw_path).exists():
            frameworks[case["id"]] = Path(fw_path).read_text()
            print(f"  {case['domain']}: loaded from cache")
        else:
            print(f"  {case['domain']}: generating...", end=" ", flush=True)
            fw = generate_framework(case["domain"], case["task"])
            Path(fw_path).write_text(f"# Framework: {case['domain']}\n\n{fw}")
            frameworks[case["id"]] = fw
            print("done")
            time.sleep(1)

    # Run benchmark
    total = len(cases) * len(models) * 3  # cases × models × conditions
    count = 0

    for model in models:
        model_short = "haiku" if "haiku" in model else "sonnet"
        print(f"\n{'=' * 70}")
        print(f"MODEL: {model_short.upper()}")
        print(f"{'=' * 70}")

        for case in cases:
            print(f"\n  Case: {case['domain']} ({case['id']})")

            for cond_name, prompt_fn in [
                ("PE", lambda c: get_pe_prompt(c)),
                ("CE", lambda c: get_ce_prompt(c)),
                ("FI", lambda c: get_fi_prompt(c, frameworks[c["id"]]))
            ]:
                count += 1
                print(f"    [{count}/{total}] {cond_name}...", end=" ", flush=True)

                prompt = prompt_fn(case)
                output = run_condition(case, prompt, model)

                evaluation = evaluate_output(case, output)

                result = {
                    "case_id": case["id"],
                    "domain": case["domain"],
                    "model": model_short,
                    "condition": cond_name,
                    "output_length": len(output),
                    "evaluation": evaluation,
                    "output_preview": output[:300] + "..."
                }
                results["results"].append(result)

                total_score = evaluation.get("total", "N/A")
                print(f"Score: {total_score}")

                time.sleep(2)

    # Aggregate
    print(f"\n{'=' * 70}")
    print("RESULTS SUMMARY")
    print(f"{'=' * 70}")

    for model_name in ["haiku", "sonnet"]:
        model_results = [r for r in results["results"] if r["model"] == model_name]
        if not model_results:
            continue

        print(f"\n  MODEL: {model_name.upper()}")
        print(f"  {'Criterion':<25} {'PE':>8} {'CE':>8} {'FI':>8} {'FI-PE':>8}")
        print(f"  {'-' * 57}")

        criteria = ["domain_accuracy", "reasoning_depth", "completeness", "nuance",
                     "actionability", "hallucination_check", "professional_judgment", "total"]

        for crit in criteria:
            scores = {}
            for cond in ["PE", "CE", "FI"]:
                vals = [
                    r["evaluation"].get(crit, 0)
                    for r in model_results
                    if r["condition"] == cond and "error" not in r["evaluation"]
                ]
                scores[cond] = sum(vals) / len(vals) if vals else 0

            delta = scores["FI"] - scores["PE"]
            delta_str = f"+{delta:.2f}" if delta > 0 else f"{delta:.2f}"
            print(f"  {crit:<25} {scores['PE']:>8.2f} {scores['CE']:>8.2f} {scores['FI']:>8.2f} {delta_str:>8}")

    # Save
    results_path = f"{output_dir}/hard_benchmark_{timestamp}.json"
    Path(results_path).write_text(json.dumps(results, indent=2, ensure_ascii=False))

    summary_path = f"{output_dir}/hard_summary_{timestamp}.md"
    with open(summary_path, "w") as f:
        f.write("# PE vs CE vs FI — HARD Benchmark (Real-World Cases)\n\n")
        f.write(f"Generated: {datetime.now().isoformat()}\n\n")
        f.write(f"Cases: {len(cases)} | Models: {', '.join(m.split('-')[1] for m in models)}\n\n")

        for model_name in ["haiku", "sonnet"]:
            model_results = [r for r in results["results"] if r["model"] == model_name]
            if not model_results:
                continue

            f.write(f"## {model_name.upper()}\n\n")
            f.write("| Criterion | PE | CE | FI | FI-PE |\n")
            f.write("|-----------|----|----|----|---------|\n")

            for crit in criteria:
                scores = {}
                for cond in ["PE", "CE", "FI"]:
                    vals = [
                        r["evaluation"].get(crit, 0)
                        for r in model_results
                        if r["condition"] == cond and "error" not in r["evaluation"]
                    ]
                    scores[cond] = sum(vals) / len(vals) if vals else 0

                delta = scores["FI"] - scores["PE"]
                delta_str = f"+{delta:.2f}" if delta > 0 else f"{delta:.2f}"
                f.write(f"| {crit} | {scores['PE']:.2f} | {scores['CE']:.2f} | {scores['FI']:.2f} | {delta_str} |\n")

            f.write("\n")

    print(f"\nResults saved to: {results_path}")
    print(f"Summary saved to: {summary_path}")
    return results


