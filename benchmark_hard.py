HARD_EVAL_PROMPT = """You are a senior domain expert evaluating a professional analysis. Be STRICT. A score of 5 means genuinely expert-level work. A score of 3 means competent but missing important elements. A score of 1 means inadequate.

Domain: {domain}
Task: {task}
Source: {source}

EVALUATION CRITERIA (rate each 1-5, be strict):

1. DOMAIN_ACCURACY — Are facts, legal citations, technical concepts correct? Any errors?
2. REASONING_DEPTH — Multi-step reasoning? Consideration of second-order effects? Non-obvious insights?
3. COMPLETENESS — All important aspects addressed? Expected elements: {criteria}
4. NUANCE — Does the analysis handle ambiguity, conflicting interests, and uncertainty appropriately?
5. ACTIONABILITY — Are recommendations specific, prioritized, and implementable?
6. HALLUCINATION_CHECK — Any fabricated citations, invented precedents, or false facts? (5=none, 1=significant)
7. PROFESSIONAL_JUDGMENT — Would a senior practitioner consider this analysis credible and useful?

Analysis to evaluate:
---
{output}
---

Respond ONLY with JSON:
{{"domain_accuracy": X, "reasoning_depth": X, "completeness": X, "nuance": X, "actionability": X, "hallucination_check": X, "professional_judgment": X, "total": X, "strengths": "...", "weaknesses": "...", "missed_elements": ["..."]}}"""


def evaluate_output(case: dict, output: str, eval_model: str = "claude-sonnet-4-6") -> dict:
    """Evaluate using stricter criteria."""
    client = anthropic.Anthropic()

    message = client.messages.create(
        model=eval_model,
        max_tokens=1500,
        messages=[{
            "role": "user",
            "content": HARD_EVAL_PROMPT.format(
                domain=case["domain"],
                task=case["task"],
                source=case["source"],
                criteria=", ".join(case["expert_criteria"]),
                output=output
            )
        }]
    )

    try:
        text = message.content[0].text
        start = text.index("{")
        end = text.rindex("}") + 1
        return json.loads(text[start:end])
    except (ValueError, json.JSONDecodeError):
        return {"error": "parse_failed", "raw": text[:500]}


def run_condition(case: dict, prompt: str, model: str) -> str:
    """Run a single condition."""
    client = anthropic.Anthropic()

    message = client.messages.create(
        model=model,
        max_tokens=6000,
        temperature=0.7,
        messages=[{"role": "user", "content": prompt}]
    )
    return message.content[0].text


