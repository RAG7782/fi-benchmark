"""
Framework Injection Generator v1.0

Generates complete injectable frameworks for any domain using
the Digital Craftsmanship methodology.

Usage:
    python fi_generator.py --domain "corporate law M&A due diligence"
    python fi_generator.py --domain "clinical cardiology diagnosis" --output framework.md
"""

import anthropic
import argparse
import json
import os
from pathlib import Path

# The meta-framework that GENERATES frameworks
# This is Framework Injection applied to itself — FI generating FI
META_FRAMEWORK = """You are a Framework Injection specialist operating under the Digital Craftsmanship methodology.

Your task: generate a complete, injectable reasoning framework for the domain described below.

The framework must contain ALL FIVE types:

1. DECLARATIVE — Knowledge hierarchy for this domain
   - What sources of authority exist? Rank them.
   - What are the foundational concepts? Define them with HIGH semiotic density terms.
   - What taxonomies structure the domain?

2. PROCEDURAL — Step-by-step reasoning method
   - How does an expert in this domain approach a problem?
   - What is the diagnostic/analytical sequence?
   - What decision points exist and what determines each branch?

3. EVALUATIVE — Quality criteria and scoring
   - How does an expert judge if work in this domain is good?
   - What dimensions matter? (completeness, accuracy, relevance, etc.)
   - What scoring rubric would an expert use?

4. ETHICAL — Hard constraints and fences
   - What MUST NEVER be done in this domain?
   - What compliance requirements exist?
   - What safety boundaries are non-negotiable?

5. COMPOSITIONAL — How the above combine into a workflow
   - What is the end-to-end process?
   - How do the other four types interact?
   - What validation steps ensure quality?

SEMIOTIC DENSITY RULES:
- Use domain-specific terms of HIGH density (not generic verbs)
- Each key term should activate a specific professional frame
- Preserve integrity of dense terms — don't paraphrase what should be a term of art
- Design for uniform density — no sparse filler between dense sections
- Think of key terms as "semantic radicals" that color everything around them

OUTPUT FORMAT:
Generate the framework as a structured document that can be directly loaded as a system prompt or skill file. Use clear section headers. Be specific, not generic. Every sentence should carry information a domain expert would recognize as correct and useful.

DOMAIN: {domain}
"""


def generate_framework(domain: str, model: str = "claude-sonnet-4-6") -> str:
    """Generate a complete injectable framework for the given domain."""
    client = anthropic.Anthropic()

    message = client.messages.create(
        model=model,
        max_tokens=8000,
        messages=[{
            "role": "user",
            "content": META_FRAMEWORK.format(domain=domain)
        }]
    )

    return message.content[0].text


def save_framework(framework: str, domain: str, output_path: str = None) -> str:
    """Save the generated framework to a file."""
    if output_path is None:
        safe_name = domain.lower().replace(" ", "-").replace("/", "-")[:50]
        output_path = f"frameworks/{safe_name}.md"

    Path(output_path).parent.mkdir(parents=True, exist_ok=True)

    with open(output_path, "w") as f:
        f.write(f"# Framework Injection: {domain}\n\n")
        f.write(f"Generated by FI Generator v1.0\n")
        f.write(f"Methodology: Digital Craftsmanship (Gomes, 2026)\n\n")
        f.write("---\n\n")
        f.write(framework)

    return output_path


def main():
    parser = argparse.ArgumentParser(description="Framework Injection Generator")
    parser.add_argument("--domain", required=True, help="Domain description")
    parser.add_argument("--output", help="Output file path")
    parser.add_argument("--model", default="claude-sonnet-4-6", help="Model to use")
    args = parser.parse_args()

    print(f"Generating framework for: {args.domain}")
    framework = generate_framework(args.domain, args.model)
    path = save_framework(framework, args.domain, args.output)
    print(f"Framework saved to: {path}")


if __name__ == "__main__":
    main()
